def mm_to_inches(mm):
    """Convert millimeters to inches.

    Args:
    mm (float): The length in millimeters.

    Returns:
    float: The length in inches ( 1 inch = 25.4 mm).
    """
    return mm / 25.4
def inches_to_mm(inches):
    """Convert inches to millimeters.

    Args:
    inches (float): The length in inches.

    Returns:
    float: The length in millimeters ( inches * 25.4 ).
    """
    return inches * 25.4