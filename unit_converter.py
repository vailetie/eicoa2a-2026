def mm_to_inches(mm):
    """Convert millimeters to inches.

    Args:
    mm (float): The length in millimeters.

    Returns:
    float: The length in inches ( 1 inch = 25.4 mm).
    """
    return mm / 25.4
def inches_to_mm(inches):
    """Convert inches to millimeters.

    Args:
    inches (float): The length in inches.

    Returns:
    float: The length in millimeters ( inches * 25.4 ).
    """
    return inches * 25.4
def cm_to_inches(cm):
    """Convert centimeters to inches.

    Args:
    cm (float): The length in centimeters.

    Returns:
    float: The length in inches ( 1 inch = 2.54 cm).
    """
    return cm / 2.54
def inches_to_cm(inches):
    """Convert inches to centimeters.

    Args:
    inches (float): The length in inches.

    Returns:
    float: The length in centimeters ( inches * 2.54 ).
    """
    return inches * 2.54